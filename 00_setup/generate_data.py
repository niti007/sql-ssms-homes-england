def emit(table, cols, rows, go_every=5):
    lines.append("PRINT 'Loading %s (%d rows)';" % (table, len(rows)))
    n = 0
    for i in range(0, len(rows), 1000):
        chunk = rows[i:i + 1000]
        lines.append("INSERT INTO dbo.%s (%s) VALUES" % (table, ", ".join(cols)))
        lines.append(",\n".join("(" + ", ".join(r) + ")" for r in chunk) + ";")
        n += 1
        if n % go_every == 0:
            lines.append("GO")
    lines.append("GO\n")

lines.append("/* HousingDelivery - data load (generated by generate_data.py, seed 42). ALL DATA IS FICTIONAL. Do not edit by hand. */")
